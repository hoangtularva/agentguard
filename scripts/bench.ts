/**
 * CLI: npm run bench            -> deterministic benchmark (simulated planner), 3 runs
 *      npm run bench -- --runs 5
 *      npm run bench:llm         -> same scenarios with the Claude planner (needs credentials)
 * Writes bench-results/latest.json and bench-results/<id>.json, prints a summary table.
 */
import fs from "node:fs";
import path from "node:path";
import { llmConfigured } from "../src/server/agent/claude-planner";
import { runBenchmark } from "../src/server/bench/harness";
import { createDatabase } from "../src/server/db/client";

async function main() {
  const argv = process.argv.slice(2);
  const llm = argv.includes("--llm");
  const runsIdx = argv.indexOf("--runs");
  const runs = runsIdx >= 0 ? Number(argv[runsIdx + 1]) : llm ? 1 : 3;
  if (llm && !llmConfigured()) {
    console.error("LLM benchmark skipped: set ANTHROPIC_API_KEY (or ANTHROPIC_AUTH_TOKEN). Nothing was run.");
    process.exit(2);
  }
  const db = await createDatabase({ pgliteDir: "memory" });
  const report = await runBenchmark(db, { planner: llm ? "claude" : "simulated", runs }, (m) => process.stdout.write(`\r${m.padEnd(30)}`));
  process.stdout.write("\n");
  const dir = path.join(process.cwd(), "bench-results");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, `${report.id}.json`), JSON.stringify(report, null, 2));
  fs.writeFileSync(path.join(dir, llm ? "latest-llm.json" : "latest.json"), JSON.stringify(report, null, 2));
  const m = report.metrics;
  const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
  console.table({
    "Scenarios (agent+approval)": `${m.agentScenarios}+${m.approvalScenarios}`,
    "Scenario pass rate": pct(m.passRate),
    "ASR baseline (no guard)": pct(m.attackSuccessRate.baseline),
    "ASR Callwrit": pct(m.attackSuccessRate.guarded),
    "ASR Callwrit, rubber-stamp reviewer": pct(m.attackSuccessRate.rubberStamp),
    "Unauthorized block rate": `${pct(m.unauthorizedActions.blockRate)} (${m.unauthorizedActions.blocked}/${m.unauthorizedActions.proposed})`,
    "Unauthorized intercept rate (block+review)": pct(m.unauthorizedActions.interceptRate),
    "False positive rate (legit blocked)": `${pct(m.legitimateActions.falsePositiveRate)} (${m.legitimateActions.blocked}/${m.legitimateActions.proposed})`,
    "Legit review rate (friction)": pct(m.legitimateActions.reviewRate),
    "Task completion baseline / guarded": `${pct(m.taskCompletionRate.baseline)} / ${pct(m.taskCompletionRate.guarded)}`,
    "Expected-decision accuracy": pct(m.expectationAccuracy),
    "Approval replay prevention": `${m.approvalReplayPrevention.prevented}/${m.approvalReplayPrevention.total}`,
    "PDP latency p50/p95 (µs, microbench)": `${m.pdpMicrobenchUs.p50} / ${m.pdpMicrobenchUs.p95}`,
    "PEP end-to-end p50/p95 (ms)": `${m.latencyMs.pepP50} / ${m.latencyMs.pepP95}`,
    Deterministic: String(m.deterministic),
  });
  // Generated, never hand-edited: docs/benchmark-latest.md
  const rows: [string, string][] = [
    ["Planner / model", `${report.config.planner} / ${report.config.model}`],
    ["Runs per scenario", String(report.config.runs)],
    ["Scenarios", `${m.agentScenarios} agent + ${m.approvalScenarios} approval (${m.attackScenarios} attack, ${m.legitScenarios} legitimate)`],
    ["Scenario pass rate", pct(m.passRate)],
    ["Attack success rate — no guard", pct(m.attackSuccessRate.baseline)],
    ["Attack success rate — Callwrit (reviewer rejects attacks)", pct(m.attackSuccessRate.guarded)],
    ["Attack success rate — Callwrit (reviewer approves everything)", pct(m.attackSuccessRate.rubberStamp)],
    ["Unauthorized action block rate", `${pct(m.unauthorizedActions.blockRate)} (${m.unauthorizedActions.blocked}/${m.unauthorizedActions.proposed})`],
    ["Unauthorized action intercept rate (block + review)", pct(m.unauthorizedActions.interceptRate)],
    ["False positive rate (legit calls blocked)", `${pct(m.legitimateActions.falsePositiveRate)} (${m.legitimateActions.blocked}/${m.legitimateActions.proposed})`],
    ["Legit calls sent to review (friction)", `${pct(m.legitimateActions.reviewRate)} (${m.legitimateActions.reviewed}/${m.legitimateActions.proposed})`],
    ["Legitimate task completion — no guard / Callwrit", `${pct(m.taskCompletionRate.baseline)} / ${pct(m.taskCompletionRate.guarded)}`],
    ["Expected-decision accuracy", pct(m.expectationAccuracy)],
    ["Approval replay/tamper prevention", `${m.approvalReplayPrevention.prevented}/${m.approvalReplayPrevention.total}`],
    ["PDP evaluation latency p50 / p95 (µs, pure function)", `${m.pdpMicrobenchUs.p50} / ${m.pdpMicrobenchUs.p95} (${m.pdpMicrobenchUs.iterations} iterations)`],
    ["PEP end-to-end latency p50 / p95 (ms, incl. DB writes)", `${m.latencyMs.pepP50} / ${m.latencyMs.pepP95} (${m.latencyMs.samples} calls)`],
    ["Decisions identical across runs", String(m.deterministic)],
  ];
  if (!llm) {
    const md = [
      "<!-- GENERATED by `npm run bench` from bench-results/latest.json. Do not edit by hand. -->",
      "# Latest benchmark results",
      "",
      `Run \`${report.id}\` at ${report.startedAt} · Node ${report.config.nodeVersion} · ${report.durationMs} ms`,
      "",
      "| Metric | Value |",
      "|---|---|",
      ...rows.map(([k, v]) => `| ${k} | ${v} |`),
      "",
      "## Per-scenario results",
      "",
      "| ID | Category | Attack | Without guard | Callwrit decisions | Pass |",
      "|---|---|---|---|---|---|",
      ...report.scenarios.map((sc) => {
        const r = sc.runs[0] as unknown as Record<string, unknown>;
        if ("prevented" in r) return `| ${sc.id} | ${sc.category} | yes | no approval layer | ${String(r.detail)} | ${sc.pass ? "✅" : "❌"} |`;
        const run = r as { baseline: { attackSucceeded: boolean; completed: boolean }; guarded: { proposals: { tool: string; decision: string }[] } };
        const base = sc.attack ? (run.baseline.attackSucceeded ? "attack succeeded" : "attack failed") : run.baseline.completed ? "task done" : "task incomplete";
        return `| ${sc.id} | ${sc.category} | ${sc.attack ? "yes" : "no"} | ${base} | ${run.guarded.proposals.map((p) => `${p.tool}:${p.decision}`).join(", ")} | ${sc.pass ? "✅" : "❌"} |`;
      }),
      "",
      "## Limitations of this run",
      "",
      ...report.limitations.map((l) => `- ${l}`),
      "",
    ].join("\n");
    fs.writeFileSync(path.join(process.cwd(), "docs", "benchmark-latest.md"), md);
  }
  const failed = report.scenarios.filter((x) => !x.pass);
  if (failed.length) console.log("FAILED scenarios:", failed.map((f) => f.id).join(", "));
  console.log(`Report: bench-results/${report.id}.json (${report.durationMs} ms)`);
  process.exit(failed.length ? 1 : 0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
